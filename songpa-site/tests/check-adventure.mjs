import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {createEngine} from '../src/shared/engine.mjs';
const D=JSON.parse(fs.readFileSync('dist/client/pokemon-data.json'));
const C=JSON.parse(fs.readFileSync('dist/client/game-settings.json'));
const W=JSON.parse(fs.readFileSync('dist/client/world-seed.json'));
const E=createEngine(D,C,W),s=E.migrate(null,1000,983452);
E.apply(s,'demo',{},1000);E.apply(s,'starter',{id:749},1000);
assert.equal(E.adventure(s).filter(g=>g.ready).length,0);
assert.throws(()=>E.apply(s,'claim-goal',{id:'first-arrival'},1000));
const dest=W.facilities[0];
E.apply(s,'start',{plan:{origin:s.game.coord,destinationId:dest.id,destinationCoord:dest.coord,geometry:[s.game.coord,dest.coord],durationMs:1000,distanceM:E.distance(s.game.coord,dest.coord),mode:'walk'}},1000);
E.advance(s,2000);
assert(E.adventure(s).find(g=>g.id==='first-arrival').ready);
const before=s.player.money;
E.apply(s,'claim-goal',{id:'first-arrival',reward:{money:999999}},2001);
assert.equal(s.player.money,before+200,'Rewards come from the engine, not the request');
assert.throws(()=>E.apply(s,'claim-goal',{id:'first-arrival'},2002));
const restored=E.migrate(s,3000);
assert(E.adventure(restored).find(g=>g.id==='first-arrival').claimed);
assert.throws(()=>E.apply(restored,'claim-goal',{id:'first-arrival'},3000));
// Repeated species do not advance the collection goal; distinct owned species do.
for(let i=0;i<5;i++)s.box.push(E.newPokemon(s,19,5,3000));
assert.equal(E.adventure(s).find(g=>g.id==='collect-5').progress,2);
for(const id of [25,281,133])s.box.push(E.newPokemon(s,id,5,3000));
const balls=s.bag['great-ball'];E.apply(s,'claim-goal',{id:'collect-5'},3001);
assert.equal(s.bag['great-ball'],balls+3);

// UI search is exercised with real owned records and the shared Pokémon data.
