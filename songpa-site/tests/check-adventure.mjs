const panels={'panel-team':new El('section'),'adventure-content':new El('div')};
const context=vm.createContext({window:{},game:s,D,C,E,ready:true,busy:false,$:id=>panels[id],node:(...a)=>{const e=new El(a[0]);e.textContent=a[1];e.className=a[2];return e;},button:(label,fn,disabled)=>Object.assign(new El('button'),{textContent:label,onclick:fn,disabled}),pokemonCard:p=>Object.assign(new El('article'),{uid:p.uid}),showTab(){},action(){}});
vm.runInContext(fs.readFileSync('dist/client/adventure-ui.js','utf8'),context);
vm.runInContext('renderTeam();',context);
const originalUids=s.box.map(p=>p.uid);
assert.equal(vm.runInContext("boxView.query='25';matchingBox().length",context),1);
assert.equal(vm.runInContext("boxView.query='PIKACHU';matchingBox()[0].speciesId",context),25);
assert.equal(vm.runInContext("boxView.query='피카';matchingBox()[0].speciesId",context),25);
assert.equal(vm.runInContext("boxView.query='없는포켓몬';matchingBox().length",context),0);
s.box[0].shiny=true;s.box[1].hp=0;
assert.equal(vm.runInContext("boxView.query='';boxView.filter='shiny';matchingBox().length",context),1);
assert.equal(vm.runInContext("boxView.filter='fainted';matchingBox().length",context),1);
s.box[0].level=12;
assert.equal(vm.runInContext("boxView.filter='all';boxView.sort='level';matchingBox()[0].level",context),12);
const ordered=vm.runInContext("boxView.sort='dex';matchingBox().map(p=>p.speciesId).join(',')",context).split(',').map(Number);
assert(ordered.every((id,i)=>!i||ordered[i-1]<=id));
assert.deepEqual(s.box.map(p=>p.uid),originalUids,'Search and sorting never reorder owned state');
const search=vm.runInContext('teamView.search',context);search.value='25';search.oninput();
vm.runInContext('renderTeam();',context);assert.equal(vm.runInContext('teamView.search',context),search,'Background saves retain the search input and focus target');
assert.equal(search.value,'25');
for(let i=0;i<30;i++)s.box.push(E.newPokemon(s,19,5,4000));
vm.runInContext("boxView.query='';boxView.filter='all';renderBox();",context);
